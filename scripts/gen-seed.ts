// Writes supabase/seed.sql from the species table in packages/core.
// Run: npm run gen:seed
import { writeFileSync } from "node:fs";
import { SPECIES } from "../packages/core/src/species.ts";

const q = (v: string | null) => (v === null ? "null" : `'${v.replaceAll("'", "''")}'`);

const rows = SPECIES.map(
  (s) =>
    `  (${q(s.id)}, ${q(s.name)}, ${q(s.plural)}, ${s.idealTideFt}, ${s.marginalTideFt}, ${q(s.tideSource)}, ` +
    `${s.hoursBeforeLow}, ${s.hoursAfterLow}, ${q(s.seasonGroup)}, ${q(s.region)}, ${q(s.dailyLimit)}, ${q(s.minSize)}, ${q(s.notes)})`,
);

const sql = `-- Generated by scripts/gen-seed.ts from packages/core/src/species.ts. Do not edit by hand.
insert into species (id, name, plural, ideal_tide_ft, marginal_tide_ft, tide_source, hours_before_low, hours_after_low, season_group, region, daily_limit, min_size, notes)
values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name, plural = excluded.plural, ideal_tide_ft = excluded.ideal_tide_ft,
  marginal_tide_ft = excluded.marginal_tide_ft, tide_source = excluded.tide_source,
  hours_before_low = excluded.hours_before_low, hours_after_low = excluded.hours_after_low,
  season_group = excluded.season_group, region = excluded.region, daily_limit = excluded.daily_limit,
  min_size = excluded.min_size, notes = excluded.notes;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${SPECIES.length} species to supabase/seed.sql`);
